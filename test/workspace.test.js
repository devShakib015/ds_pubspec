'use strict';

// Pub workspaces: one lock at the root, members that aren't in it, and
// sibling names that must never be looked up on pub.dev.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { resolveLock, workspaceEntries } = require('../lib/workspace');
const { analyze } = require('../lib/analyze');
const { makeWorld, lockFor, fakePubDev, write } = require('./helpers');

function workspace() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-pubspec-ws-'));
  write(path.join(root, 'pubspec.yaml'),
    'name: tools\nenvironment:\n  sdk: ^3.8.0\n\nworkspace:\n  - apps/notes # the app\n  - "packages/*"\n\ndev_dependencies:\n  lints: ^6.0.0\n');
  write(path.join(root, 'apps', 'notes', 'pubspec.yaml'),
    'name: notes\nresolution: workspace\ndependencies:\n  flutter:\n    sdk: flutter\n  ui: any\n  later: any\n');
  // notes -> ui -> core -> cam: two members deep before the plugin.
  write(path.join(root, 'packages', 'ui', 'pubspec.yaml'), 'name: ui\nresolution: workspace\ndependencies:\n  core: any\n');
  write(path.join(root, 'packages', 'core', 'pubspec.yaml'), 'name: core\nresolution: workspace\ndependencies:\n  cam: ^1.0.0\n');
  // A sibling that happens to share its name with a pub.dev package.
  write(path.join(root, 'packages', 'later', 'pubspec.yaml'), 'name: later\nresolution: workspace\n');
  fs.mkdirSync(path.join(root, 'apps', 'notes', 'ios'), { recursive: true });
  return { root, cleanup: () => fs.rmSync(root, { recursive: true, force: true }) };
}

test('workspaceEntries: plain, quoted, commented, and where the list ends', () => {
  assert.deepEqual(workspaceEntries('name: x\nworkspace:\n  - a\n  - "b/*" # all\n  - \'c\'\nenvironment:\n  - not_this\n'), ['a', 'b/*', 'c']);
  assert.deepEqual(workspaceEntries('name: x\n'), []);
});

test('resolveLock: a member climbs to the root lock; members found through globs', () => {
  const ws = workspace();
  try {
    const app = path.join(ws.root, 'apps', 'notes');
    const r = resolveLock(app, fs.readFileSync(path.join(app, 'pubspec.yaml'), 'utf8'));
    assert.equal(r.lockPath, path.join(ws.root, 'pubspec.lock'));
    assert.deepEqual([...r.members.keys()].sort(), ['core', 'later', 'notes', 'ui']);
    const plain = resolveLock('/nowhere/app', 'name: app\n');
    assert.equal(plain.lockPath, path.join('/nowhere/app', 'pubspec.lock'));
    assert.equal(plain.members.size, 0);
  } finally { ws.cleanup(); }
});

test('a member app: plugins traced through a sibling package, sibling names kept off pub.dev', async () => {
  const ws = workspace();
  const cache = makeWorld({ packages: {
    cam: { version: '1.0.0', plugin: { ios: { pluginClass: 'Cam' } }, files: { 'ios/cam.podspec': 'x' } },
  } });
  try {
    const app = path.join(ws.root, 'apps', 'notes');
    const pubspecText = fs.readFileSync(path.join(app, 'pubspec.yaml'), 'utf8');
    const { lockPath, members } = resolveLock(app, pubspecText);
    const asked = [];
    const pubdev = fakePubDev({ packages: { later: { latest: '9.0.0', isDiscontinued: true }, cam: { latest: '1.0.0' } } });
    const spy = { packageInfo: (n) => { asked.push(n); return pubdev.packageInfo(n); }, scoreInfo: (n) => pubdev.scoreInfo(n) };
    const r = await analyze({
      pubspecText, lockText: lockFor({ cam: '1.0.0', lints: '6.0.0' }), projectDir: app,
      lockDir: path.dirname(lockPath), members, cacheDir: cache.cacheDir, pubdev: spy,
    });
    assert.deepEqual(r.findings.map((f) => `${f.id}:${f.dep}`), ['swiftpm:ui'], 'cam reaches the app through ui');
    assert.ok(!asked.includes('later') && !asked.includes('ui'), `asked pub.dev about: ${asked}`);
    assert.ok(!r.onPubDev.has('later'));

    // Before the first pub get there's no lock to go by, only the members.
    asked.length = 0;
    const fresh = await analyze({
      pubspecText, lockText: null, projectDir: app, lockDir: path.dirname(lockPath), members,
      cacheDir: cache.cacheDir, pubdev: spy,
    });
    assert.deepEqual(fresh.findings.map((f) => f.id), ['not-resolved']);
    assert.deepEqual(asked, [], 'no lock yet, and still nothing about siblings asked of pub.dev');
  } finally { ws.cleanup(); cache.cleanup(); }
});

test('with a lock, a name pub resolved from a path is not a pub.dev package', async () => {
  const w = makeWorld();
  try {
    const lock = '# Generated by pub\npackages:\n  forked:\n    dependency: "direct main"\n    description:\n      path: "../forked"\n      relative: true\n    source: path\n    version: "1.0.0"\nsdks:\n  dart: ">=3.8.0 <4.0.0"\n';
    const r = await analyze({
      pubspecText: 'name: app\ndependencies:\n  forked: ^1.0.0\n', lockText: lock,
      projectDir: w.projectDir, cacheDir: w.cacheDir,
      pubdev: fakePubDev({ packages: { forked: { latest: '2.0.0', isDiscontinued: true } } }),
    });
    assert.deepEqual(r.findings, []);
  } finally { w.cleanup(); }
});

test('a vendored package is checked against the lock of the app that resolved it', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-pubspec-vendor-'));
  try {
    write(path.join(root, 'pubspec.yaml'), 'name: site\ndependencies:\n  icons:\n    path: third_party/icons\n');
    write(path.join(root, 'pubspec.lock'), '# Generated by pub\npackages:\n  icons:\n    dependency: "direct main"\n'
      + '    description:\n      path: "third_party/icons"\n      relative: true\n    source: path\n    version: "1.0.0"\n'
      + 'sdks:\n  dart: ">=3.8.0 <4.0.0"\n');
    const vendored = path.join(root, 'third_party', 'icons');
    write(path.join(vendored, 'pubspec.yaml'), 'name: icons\ndependencies:\n  meta: ^1.0.0\n');
    write(path.join(root, 'other', 'pubspec.yaml'), 'name: other\n');
    assert.equal(resolveLock(vendored, 'name: icons\n').lockPath, path.join(root, 'pubspec.lock'));
    assert.equal(resolveLock(path.join(root, 'other'), 'name: other\n').lockPath, path.join(root, 'other', 'pubspec.lock'),
      'not resolved by the root lock: its own (missing) lock');
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});
