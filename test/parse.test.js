'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { parsePubspec } = require('../lib/pubspec');
const { parseLock } = require('../lib/lockfile');
const { parseYamlMaps } = require('../lib/yamlmap');
const { compareVersions } = require('../lib/semver');

test('pubspec: hosted, sdk, path, git and custom-hosted entries, with positions', () => {
  const { name, deps } = parsePubspec([
    'name: my_app',
    'description: "An app # not a comment"',
    'dependencies:',
    '  flutter:',
    '    sdk: flutter',
    '  http: ^1.2.0 # the comment goes',
    '  "quoted_pkg": 2.0.0',
    '  local_thing:',
    '    path: ../local_thing',
    '  from_git:',
    '    git:',
    '      url: https://github.com/a/b.git',
    '  private_pkg:',
    '    hosted: https://dart.example.com',
    '    version: ^3.0.0',
    '  inline: {path: ../inline}',
    '  bare:',
    '',
    'dev_dependencies:',
    '  lints: any',
    'flutter:',
    '  uses-material-design: true',
  ].join('\n'));

  assert.equal(name, 'my_app');
  const by = Object.fromEntries(deps.map((d) => [d.name, d]));
  assert.deepEqual(Object.keys(by), ['flutter', 'http', 'quoted_pkg', 'local_thing', 'from_git', 'private_pkg', 'inline', 'bare', 'lints']);
  assert.equal(by.flutter.source, 'sdk');
  assert.equal(by.http.constraint, '^1.2.0');
  assert.equal(by.http.line, 5);
  assert.equal(by.http.start, 2);
  assert.equal(by.http.end, 6);
  assert.equal(by.quoted_pkg.start, 3, 'the name, not the quote');
  assert.equal(by.local_thing.source, 'path');
  assert.equal(by.local_thing.path, '../local_thing');
  assert.equal(by.from_git.source, 'git');
  assert.equal(by.private_pkg.hostedUrl, 'https://dart.example.com');
  assert.equal(by.private_pkg.constraint, '^3.0.0');
  assert.equal(by.inline.source, 'path');
  assert.equal(by.bare.source, 'hosted');
  assert.equal(by.bare.constraint, null);
  assert.equal(by.lints.section, 'dev_dependencies');
});

test('pubspec: tab-free 4-space indentation and a hosted map with url', () => {
  const { deps } = parsePubspec([
    'dependencies:',
    '    a: ^1.0.0',
    '    b:',
    '        hosted:',
    '            name: b',
    '            url: https://pub.example.com',
    '        version: ^2.0.0',
  ].join('\n'));
  assert.deepEqual(deps.map((d) => d.name), ['a', 'b']);
  assert.equal(deps[1].hostedUrl, 'https://pub.example.com');
  assert.equal(deps[1].constraint, '^2.0.0');
});

test('lockfile: hosted, sdk, path and git packages', () => {
  const lock = parseLock([
    '# Generated by pub',
    'packages:',
    '  async:',
    '    dependency: transitive',
    '    description:',
    '      name: async',
    '      sha256: "abc"',
    '      url: "https://pub.dev"',
    '    source: hosted',
    '    version: "2.13.0"',
    '  flutter:',
    '    dependency: "direct main"',
    '    description: flutter',
    '    source: sdk',
    '    version: "0.0.0"',
    '  local_thing:',
    '    dependency: "direct main"',
    '    description:',
    '      path: "../local_thing"',
    '      relative: true',
    '    source: path',
    '    version: "1.0.0"',
    '  from_git:',
    '    dependency: "direct main"',
    '    description:',
    '      path: "."',
    '      ref: HEAD',
    '      resolved-ref: "deadbeef"',
    '      url: "https://github.com/a/from_git.git"',
    '    source: git',
    '    version: "0.1.0"',
    'sdks:',
    '  dart: ">=3.8.0 <4.0.0"',
  ].join('\n'));
  assert.equal(lock.get('async').version, '2.13.0');
  assert.equal(lock.get('async').url, 'https://pub.dev');
  assert.equal(lock.get('flutter').source, 'sdk');
  assert.equal(lock.get('flutter').dependency, 'direct main');
  assert.equal(lock.get('local_thing').relative, true);
  assert.equal(lock.get('from_git').resolvedRef, 'deadbeef');
  assert.equal(lock.has('dart'), false, 'the sdks block is not a package');
});

test('yaml maps: nested plugin platforms, skipping block scalars and lists', () => {
  const y = parseYamlMaps([
    'name: some_plugin',
    'description: >-',
    '  A long description: with colons',
    '  over two lines.',
    'topics:',
    '  - camera',
    'flutter:',
    '  plugin:',
    '    platforms:',
    '      ios:',
    '        pluginClass: SomePlugin',
    '      web:',
    '        pluginClass: SomeWeb',
    '        fileName: some_web.dart',
    'repository: https://github.com/a/b',
  ].join('\n'));
  assert.equal(y.name, 'some_plugin');
  assert.equal(y.description, '');
  assert.equal(y.flutter.plugin.platforms.ios.pluginClass, 'SomePlugin');
  assert.equal(y.flutter.plugin.platforms.web.fileName, 'some_web.dart');
  assert.equal(y.repository, 'https://github.com/a/b');
});

test('semver: pre-releases sort before, build numbers after', () => {
  assert.ok(compareVersions('1.2.3', '1.2.4') < 0);
  assert.ok(compareVersions('1.10.0', '1.9.0') > 0);
  assert.ok(compareVersions('2.0.0-dev.1', '2.0.0') < 0);
  assert.ok(compareVersions('2.0.0-dev.2', '2.0.0-dev.10') < 0);
  assert.ok(compareVersions('0.6.4+3', '0.6.4') > 0);
  assert.ok(compareVersions('1.6.0+hotfix.1', '1.6.0+hotfix.2') < 0);
  assert.equal(compareVersions('3.0.0', '3.0.0'), 0);
});
