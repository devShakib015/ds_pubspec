'use strict';

// Builds a throwaway Flutter project and pub cache on disk for one test, and a
// pub.dev client that answers from a table instead of the network.

const fs = require('fs');
const os = require('os');
const path = require('path');

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

/**
 * @param {{
 *   platforms?: string[],                 // app folders to create: ios, android, macos
 *   gradleProperties?: string,
 *   packages?: Record<string, {
 *     version: string,
 *     repository?: string,
 *     deps?: string[],
 *     plugin?: Record<string, Record<string, string>>,  // platform -> keys
 *     files?: Record<string, string>,                   // relative path -> contents
 *   }>,
 * }} spec
 */
function makeWorld(spec = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-pubspec-'));
  const projectDir = path.join(root, 'app');
  const cacheDir = path.join(root, 'cache');
  fs.mkdirSync(projectDir, { recursive: true });
  for (const p of spec.platforms || []) fs.mkdirSync(path.join(projectDir, p), { recursive: true });
  if (spec.gradleProperties) write(path.join(projectDir, 'android', 'gradle.properties'), spec.gradleProperties);

  for (const [name, pkg] of Object.entries(spec.packages || {})) {
    const dir = path.join(cacheDir, 'hosted', 'pub.dev', `${name}-${pkg.version}`);
    let yaml = `name: ${name}\nversion: ${pkg.version}\n`;
    if (pkg.repository) yaml += `repository: ${pkg.repository}\n`;
    if (pkg.deps && pkg.deps.length) yaml += `dependencies:\n${pkg.deps.map((d) => `  ${d}: any\n`).join('')}`;
    if (pkg.plugin) {
      yaml += 'flutter:\n  plugin:\n    platforms:\n';
      for (const [platform, keys] of Object.entries(pkg.plugin)) {
        yaml += `      ${platform}:\n${Object.entries(keys).map(([k, v]) => `        ${k}: ${v}\n`).join('')}`;
      }
    }
    write(path.join(dir, 'pubspec.yaml'), yaml);
    for (const [rel, text] of Object.entries(pkg.files || {})) write(path.join(dir, rel), text);
  }
  return { root, projectDir, cacheDir, cleanup: () => fs.rmSync(root, { recursive: true, force: true }) };
}

/** A pubspec.lock for the given name -> version map, all hosted on pub.dev. */
function lockFor(versions, direct = []) {
  let out = '# Generated by pub\npackages:\n';
  for (const [name, version] of Object.entries(versions)) {
    out += `  ${name}:\n    dependency: ${direct.includes(name) ? '"direct main"' : 'transitive'}\n`
      + `    description:\n      name: ${name}\n      sha256: "00"\n      url: "https://pub.dev"\n`
      + `    source: hosted\n    version: "${version}"\n`;
  }
  return `${out}sdks:\n  dart: ">=3.8.0 <4.0.0"\n`;
}

/** pub.dev, answered from tables. */
function fakePubDev({ packages = {}, scores = {} } = {}) {
  return {
    packageInfo: async (name) => {
      const p = packages[name];
      if (!p) return null;
      return {
        name, latest: p.latest || null, isDiscontinued: !!p.isDiscontinued,
        replacedBy: p.replacedBy || null, retracted: p.retracted || [], published: null,
      };
    },
    scoreInfo: async (name) => {
      const s = scores[name];
      return s ? { grantedPoints: 160, maxPoints: 160, likes: 1, downloads30d: 10, tags: s.tags || [] } : null;
    },
  };
}

module.exports = { makeWorld, lockFor, fakePubDev, write };
